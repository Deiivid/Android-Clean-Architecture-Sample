import es.davidnavarro.androidcleanarchitecture.core.model.Location

internal fun locationArtwork(location: Location): Int {
    val exactIndex = location.id - 1
    if (exactIndex in LOCATION_ARTWORK.indices) {
        return LOCATION_ARTWORK[exactIndex]
    }
    return LOCATION_ARTWORK[Math.floorMod(location.id, LOCATION_ARTWORK.size)]
}

internal fun locationDetailArtwork(location: Location): Int {
    val exactIndex = location.id - 1
    if (exactIndex in LOCATION_DETAIL_ARTWORK.indices) {
        return LOCATION_DETAIL_ARTWORK[exactIndex]
    }
    return LOCATION_DETAIL_ARTWORK[Math.floorMod(location.id, LOCATION_DETAIL_ARTWORK.size)]
}

